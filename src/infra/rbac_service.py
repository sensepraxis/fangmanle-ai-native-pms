def get_role_or_raise(db: Session, code: str) -> Role:
    from domain import NotFoundError

    r = db.query(Role).filter_by(code=code).first()
    if not r:
        raise NotFoundError(f"角色不存在：{code}")
    return r


def role_public_dict(db: Session, r: Role) -> dict:
    from infra.i18n import t as _t

    return {
        "id": r.id,
        "code": r.code,
        "name": _t(r.name or ""),
        "description": _t(r.description or "") if r.description else "",
        "is_system": r.code in SYSTEM_ROLE_CODES,
        "permission_count": len(role_codes_snapshot(db, r.code)),
        "user_count": db.query(User).filter(User.role_id == r.id).count(),
    }


def user_public_dict(u: User, role: Optional[Role]) -> dict:
    from api_common import row_to_dict
    from infra.i18n import t as _t

    d = row_to_dict(u)
    d.pop("password_hash", None)
    d["role_code"] = role.code if role else ""
    d["role_name"] = _t(role.name) if role and role.name else ""
    if d.get("full_name"):
        d["full_name"] = _t(str(d["full_name"]))
    return d


def list_roles_enriched(db: Session) -> list[dict]:
    return [role_public_dict(db, r) for r in list_all_roles(db)]


def list_users_enriched(db: Session) -> list[dict]:
    users = db.query(User).order_by(User.id.asc()).all()
    role_map = {r.id: r for r in db.query(Role).all()}
    return [user_public_dict(u, role_map.get(u.role_id)) for u in users]


def reset_role_defaults(db: Session, role_code: str) -> dict:
    """系统角色恢复默认矩阵；自定义角色清空权限。"""
    role = get_role_or_raise(db, role_code)
    if role.code in SYSTEM_ROLE_CODES:
        n = apply_default_matrix(db, role_code, force=True)
    else:
        n = set_role_permission_codes(db, role_code, [])
    db.flush()
    return {"role_code": role_code, "restored": n, "codes": role_codes_snapshot(db, role_code)}


def create_user_account(
    db: Session,
    *,
    hotel_id: int,
    username: str,
    password: str,
    role_code: str,
    full_name: str = "",
    phone: str = "",
    is_active: bool = True,
    actor_role: str = "",
) -> dict:
    from domain import AuthorizationError, ConflictError, ValidationError
    from infra.auth_local import hash_password
    from models import Hotel

    username = (username or "").strip()
    if not username or not password:
        raise ValidationError("用户名与密码必填")
    if db.query(User).filter_by(username=username).first():
        raise ConflictError("用户名已存在")
    role_code = (role_code or "").strip()
    if role_code == "admin" and actor_role != "admin":
        raise AuthorizationError("仅系统管理员可创建管理员账号")
    role = get_role_or_raise(db, role_code)
    hotel = db.get(Hotel, hotel_id) or db.query(Hotel).order_by(Hotel.id).first()
    u = User(
        hotel_id=hotel.id if hotel else hotel_id,
        role_id=role.id,
        username=username,
        password_hash=hash_password(password),
        full_name=(full_name or username).strip(),
        phone=(phone or "").strip() or None,
        is_active=bool(is_active),
    )
    db.add(u)
    db.flush()
    db.refresh(u)
    return user_public_dict(u, role)


def update_user_account(
    db: Session,
    user_id: int,
    *,
    actor_role: str = "",
    actor_user_id: Optional[int] = None,
    full_name: Optional[str] = None,
    role_code: Optional[str] = None,
    phone: Optional[str] = None,
    is_active: Optional[bool] = None,
    password: Optional[str] = None,
) -> dict:
    from domain import AuthorizationError, NotFoundError, ValidationError
    from infra.auth_local import hash_password

    u = db.get(User, user_id)
    if not u:
        raise NotFoundError("用户不存在")
    if role_code is not None:
        rc = role_code.strip()
        if rc == "admin" and actor_role != "admin":
            raise AuthorizationError("仅系统管理员可分配管理员角色")
        if u.username == "admin" and rc != "admin":
            raise ValidationError("内置 admin 账号不可更改角色")
        u.role_id = get_role_or_raise(db, rc).id
    if full_name is not None:
        u.full_name = full_name.strip() or u.full_name
    if phone is not None:
        u.phone = phone.strip() or None
    if is_active is not None:
        if u.username == "admin" and not is_active:
            raise ValidationError("内置 admin 账号不可停用")
        if actor_user_id is not None and u.id == actor_user_id and not is_active:
            raise ValidationError("不能停用当前登录账号")
        u.is_active = bool(is_active)
    if password:
        u.password_hash = hash_password(password)
    db.flush()
    db.refresh(u)
    role = db.get(Role, u.role_id) if u.role_id else None
    return user_public_dict(u, role)
